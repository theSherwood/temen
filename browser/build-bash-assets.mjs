// Build the **GNU bash playground artifacts** (#1080) and stage them into `web/assets/` — the
// deploy-built counterpart of `build-pg-assets.mjs`, split the same way:
//
//   • CODE-INDEPENDENT INPUT (cached) — the whole-program bash bitcode (`bash_linked.ll`, via
//     `demos/bash/build_bitcode.sh`: fetch bash-5.2.21 from ftp.gnu.org → configure → native oracle →
//     per-TU bitcode → llvm-link + bash_shim + the reused waist). bash is **GPLv3 and never vendored
//     or committed** — this input is fetched and built at deploy, and the staged `bash.temen` stays
//     out of the tree (`web/assets/*.temen` is gitignored; there is deliberately no `!` exception).
//
//   • CODE-COUPLED OUTPUT (regenerated every run) — `web/assets/bash.temen` via `temen-llvm-translate`.
//     The flags are load-bearing, not preference:
//       --host-page 65536   the playground runs on a 64 KiB wasm host page (D40 RO/RW page isolation);
//       --stub-externs      trap-stub the OS surface bash never reaches (its live surface binds to the
//                           temen-posix ops by name — the personality vtable coverage walk);
//       --null-guard        REQUIRED for external commands to receive argv: the /bin coreutils are
//                           guarded (chibicc --child-entry, guard 16384), so their args base is
//                           guard+128 = 16512 — bash's execve must pack the child argv at the SAME
//                           base, which it only does when bash itself is guarded. A guard-0 bash
//                           writes argv at 128 and `commit_fresh_image` zeroes it: every external
//                           command then runs argv-less (`seq` errors, `echo` prints "\n").
//
//   • The **/bin registry** — the 13 repo-owned coreutils (`bin_*.temen`, chibicc-compiled,
//     64 KiB-page `--child-entry` command modules) copied from the committed test fixtures
//     `tests/fixtures/bin_*.temen` (regenerated by `gen_browser_bash_coreutils` in
//     crates/temen/tests/c_shell.rs). No toolchain needed for this half.
//
// Usage:  node build-bash-assets.mjs
//   env:  TEMEN_BASH_CACHE (default /tmp/temen_bash_cache) — the input cache (bash source + bitcode)
//         TEMEN_BASH_VER   (default 5.2.21)                — bash version (passed to build_bitcode.sh)
// Needs (only on a cold input cache): clang/llvm-link, make, curl, tar. The regenerate half
// needs only cargo + the workspace.
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';
import { existsSync, mkdirSync, copyFileSync, statSync, readdirSync } from 'node:fs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = dirname(HERE);
const ASSETS = join(HERE, 'web', 'assets');
const CACHE = process.env.TEMEN_BASH_CACHE ?? '/tmp/temen_bash_cache';
const BASHDIR = join(REPO, 'crates', 'temen-run', 'demos', 'bash');
mkdirSync(ASSETS, { recursive: true });

const env = { ...process.env, TEMEN_BASH_CACHE: CACHE };
const sh = (cmd, args, opts = {}) =>
  execFileSync(cmd, args, { stdio: 'inherit', env, cwd: REPO, ...opts });
const mb = (p) => (statSync(p).size / 1e6).toFixed(1);

// ---- 1) code-independent input: the whole-program bash bitcode (cached) ------------------------
const linkedLl = join(CACHE, 'bash_linked.ll');
if (existsSync(linkedLl)) {
  console.log(`✓ cached bitcode: bash_linked.ll (${mb(linkedLl)} MB)`);
} else {
  console.log('building bash bitcode from source (cold — fetches ftp.gnu.org, ~2-3 min)…');
  sh('bash', [join(BASHDIR, 'build_bitcode.sh')]);
  console.log(`✓ built bitcode: bash_linked.ll (${mb(linkedLl)} MB)`);
}

// ---- 2) code-coupled output: regenerate bash.temen from current Temen code every run ------------
const TR = join(REPO, 'crates', 'temen-llvm', 'target', 'release', 'temen-llvm-translate');
if (!existsSync(TR)) {
  console.log('building temen-llvm-translate…');
  sh('cargo', ['build', '--release', '--bin', 'temen-llvm-translate'], {
    cwd: join(REPO, 'crates', 'temen-llvm'),
  });
}
const bashTemen = join(ASSETS, 'bash.temen');
console.log('translating bash_linked.ll → bash.temen (--host-page 65536 --stub-externs --null-guard)…');
sh(TR, [linkedLl, '-o', bashTemen, '--binary', '--host-page', '65536', '--stub-externs', '--null-guard']);

// ---- 3) the /bin registry: copy the committed coreutil fixtures --------------------------------
const FIXTURES = join(HERE, 'tests', 'fixtures');
const bins = readdirSync(FIXTURES).filter((f) => /^bin_[a-z]+\.temen$/.test(f)).sort();
if (bins.length === 0) throw new Error(`no bin_*.temen fixtures under ${FIXTURES}`);
for (const f of bins) copyFileSync(join(FIXTURES, f), join(ASSETS, f));

console.log(
  `✓ staged web/assets/bash.temen (${mb(bashTemen)} MB) + ${bins.length} coreutils ` +
  `(${bins.map((f) => basename(f, '.temen').slice(4)).join(', ')}) — regenerated from current code`,
);
